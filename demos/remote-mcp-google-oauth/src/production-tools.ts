import { McpServer } from "@modelcontextprotocol/server";
import { z } from "zod";

const formats = ["long_form", "shorts", "tutorial", "documentary", "faceless"] as const;

/**
 * Planning and validation tools for the NEXUS video-production workflow.
 * These tools deliberately do not claim to generate media: provider adapters
 * are added separately and report unavailable until configured.
 */
export function registerProductionTools(server: McpServer) {
  server.registerTool(
    "nexus_plan_video",
    {
      description:
        "Create a structured NEXUS video-production brief and ordered workflow. Planning only: it does not generate voice, images, footage, or a rendered video.",
      inputSchema: z.object({
        concept: z.string().min(10).max(2000),
        audience: z.string().min(3).max(500),
        format: z.enum(formats),
        targetDurationMinutes: z.number().positive().max(180),
        tone: z.string().min(2).max(120).default("engaging and clear"),
        objective: z.string().min(2).max(300).default("educate and retain viewers"),
      }),
    },
    async (input) => {
      const projectId = crypto.randomUUID();
      const stages = [
        { id: "research", label: "Research and fact-check", status: "planned" },
        { id: "script", label: "Write hook, script and CTA", status: "planned" },
        { id: "storyboard", label: "Build scene-by-scene storyboard", status: "planned" },
        { id: "voice", label: "Create and review voiceover", status: "provider_required" },
        { id: "visuals", label: "Create or source visual assets", status: "provider_required" },
        { id: "edit", label: "Assemble, caption and render video", status: "render_provider_required" },
        { id: "thumbnail", label: "Create thumbnail concepts", status: "provider_required" },
        { id: "metadata", label: "Prepare title, description and tags", status: "planned" },
        { id: "approval", label: "Human review and approval", status: "required" },
        { id: "upload", label: "Upload to YouTube as PRIVATE", status: "approval_gated" },
      ];
      return {
        content: [{
          type: "text" as const,
          text: JSON.stringify({
            projectId,
            status: "brief_created",
            executionMode: "planning_only",
            brief: {
              concept: input.concept,
              audience: input.audience,
              format: input.format,
              targetDurationMinutes: input.targetDurationMinutes,
              tone: input.tone,
              objective: input.objective,
            },
            workflow: stages,
            safeguards: {
              uploadVisibility: "private",
              publicPublishingEnabled: false,
              uploadRequiresExplicitApproval: true,
            },
            note: "Voice, visual-generation and rendering stages require configured provider adapters. No media was generated by this planning tool.",
          }, null, 2),
        }],
      };
    },
  );

  server.registerTool(
    "nexus_create_storyboard",
    {
      description:
        "Turn an approved script into a timed scene outline for editing. Produces an editable plan, not image or video files.",
      inputSchema: z.object({
        script: z.string().min(50).max(30000),
        targetDurationSeconds: z.number().int().min(15).max(10800),
        aspectRatio: z.enum(["16:9", "9:16", "1:1"]).default("16:9"),
        visualDirection: z.string().max(500).default("clear, cinematic visuals"),
        maxSceneSeconds: z.number().int().min(3).max(30).default(8),
      }),
    },
    async ({ script, targetDurationSeconds, aspectRatio, visualDirection, maxSceneSeconds }) => {
      const sentences = script
        .replace(/\s+/g, " ")
        .match(/[^.!?]+[.!?]+|[^.!?]+$/g) ?? [script];
      const sceneCount = Math.max(1, Math.ceil(targetDurationSeconds / maxSceneSeconds));
      const scenes = Array.from({ length: sceneCount }, (_, index) => {
        const start = Math.floor((index * sentences.length) / sceneCount);
        const end = Math.floor(((index + 1) * sentences.length) / sceneCount);
        const narration = sentences.slice(start, Math.max(start + 1, end)).join(" ").trim();
        const duration = Math.min(maxSceneSeconds, targetDurationSeconds - index * maxSceneSeconds);
        return {
          scene: index + 1,
          startSeconds: index * maxSceneSeconds,
          durationSeconds: Math.max(1, duration),
          narration,
          visualPrompt: `${visualDirection}; illustrate: ${narration.slice(0, 240)}`,
          assetStatus: "not_generated",
        };
      });
      return {
        content: [{
          type: "text" as const,
          text: JSON.stringify({
            status: "storyboard_created",
            executionMode: "planning_only",
            aspectRatio,
            targetDurationSeconds,
            scenes,
            note: "Scene prompts are planning text only; connect an image/video provider to generate assets.",
          }, null, 2),
        }],
      };
    },
  );

  server.registerTool(
    "nexus_build_publish_package",
    {
      description:
        "Prepare a YouTube metadata draft from a video concept. Does not publish or upload anything.",
      inputSchema: z.object({
        workingTitle: z.string().min(3).max(100),
        summary: z.string().min(20).max(3000),
        keywords: z.array(z.string().min(2).max(60)).max(20).default([]),
        callToAction: z.string().max(300).default("Subscribe for more videos."),
      }),
    },
    async ({ workingTitle, summary, keywords, callToAction }) => {
      const uniqueKeywords = [...new Set(keywords.map((word) => word.trim()).filter(Boolean))];
      const hashtags = uniqueKeywords.slice(0, 3).map((word) =>
        "#" + word.replace(/[^\p{L}\p{N}_]/gu, ""),
      ).filter((word) => word.length > 1);
      const description = [
        summary.trim(),
        "",
        callToAction.trim(),
        hashtags.length ? `\n\n${hashtags.join(" ")}` : "",
      ].join("\n").trim();
      return {
        content: [{
          type: "text" as const,
          text: JSON.stringify({
            status: "metadata_draft_created",
            title: workingTitle.trim(),
            description,
            tags: uniqueKeywords,
            privacyStatus: "private",
            publishAction: "not_performed",
          }, null, 2),
        }],
      };
    },
  );

  server.registerTool(
    "nexus_check_production_readiness",
    {
      description:
        "Check whether a video project has all required production assets and approvals before a private YouTube upload.",
      inputSchema: z.object({
        scriptApproved: z.boolean(),
        voiceoverReady: z.boolean(),
        visualsReady: z.boolean(),
        finalRenderReady: z.boolean(),
        thumbnailReady: z.boolean(),
        metadataReady: z.boolean(),
        userUploadApproval: z.boolean().default(false),
      }),
    },
    async (checks) => {
      const required: Array<[keyof typeof checks, string]> = [
        ["scriptApproved", "Script approval"],
        ["voiceoverReady", "Voiceover"],
        ["visualsReady", "Visual assets"],
        ["finalRenderReady", "Final video render"],
        ["thumbnailReady", "Thumbnail"],
        ["metadataReady", "YouTube metadata"],
        ["userUploadApproval", "Explicit user upload approval"],
      ];
      const missing = required.filter(([key]) => !checks[key]).map(([, label]) => label);
      return {
        content: [{
          type: "text" as const,
          text: JSON.stringify({
            readyForPrivateUpload: missing.length === 0,
            uploadVisibility: "private",
            missingRequirements: missing,
            action: missing.length === 0 ? "private_upload_may_be_requested" : "do_not_upload",
            publicPublishingEnabled: false,
          }, null, 2),
        }],
      };
    },
  );

  server.registerTool(
    "nexus_provider_status",
    {
      description:
        "Report which media-production capabilities are implemented versus awaiting provider configuration. Never implies media generation is available when it is not.",
      inputSchema: z.object({}),
    },
    async () => ({
      content: [{
        type: "text" as const,
        text: JSON.stringify({
          capabilities: {
            videoPlanning: "available",
            storyboardPlanning: "available",
            youtubeMetadataDrafting: "available",
            productionReadinessChecks: "available",
            youtubePrivateUpload: "implemented_in_existing_tool",
            webResearch: "not_yet_integrated",
            aiVoiceGeneration: "provider_not_configured",
            imageGeneration: "provider_not_configured",
            videoGeneration: "provider_not_configured",
            videoRenderingAndEditing: "render_service_not_configured",
            thumbnailGeneration: "provider_not_configured",
            channelAnalyticsAndComments: "youtube_scopes_and_tools_not_implemented",
          },
          safety: {
            defaultVisibility: "private",
            publicPublishingEnabled: false,
            explicitUploadApprovalRequired: true,
          },
        }, null, 2),
      }],
    }),
  );
}
