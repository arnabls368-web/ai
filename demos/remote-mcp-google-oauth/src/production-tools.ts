  server.registerTool(
    "nexus_create_storyboard",
    {
      description:
        "Turn an approved script into a timed scene outline for editing. Produces an editable plan, not image or video files.",
      inputSchema: z.object({
        script: z.string().min(50).max(30000),
        targetDurationSeconds: z.number().int().min(15).max(10800),
        aspectRatio: z.enum(["16:9", "9:16", "1:1"]).default("16:9"),
        visualDirection: z.string().max(500).default("clear, cinematic visuals"),
        maxSceneSeconds: z.number().int().min(3).max(30).default(8),
        projectId: z.string().uuid().optional(),
      }),
    },
    async ({ script, targetDurationSeconds, aspectRatio, visualDirection, maxSceneSeconds, projectId }) => {
      const sentences = script
        .replace(/\s+/g, " ")
        .match(/[^.!?]+[.!?]+|[^.!?]+$/g) ?? [script];
      const sceneCount = Math.max(1, Math.ceil(targetDurationSeconds / maxSceneSeconds));
      const scenes = Array.from({ length: sceneCount }, (_, index) => {
        const start = Math.floor((index * sentences.length) / sceneCount);
        const end = Math.floor(((index + 1) * sentences.length) / sceneCount);
        const narration = sentences.slice(start, Math.max(start + 1, end)).join(" ").trim();
        const duration = Math.min(maxSceneSeconds, targetDurationSeconds - index * maxSceneSeconds);
        return {
          scene: index + 1,
          startSeconds: index * maxSceneSeconds,
          durationSeconds: Math.max(1, duration),
          narration,
          visualPrompt: `${visualDirection}; illustrate: ${narration.slice(0, 240)}`,
          assetStatus: "not_generated",
        };
      });
      if (projectId) {
        const owner = await getProjectScope();
        const key = projectKey(owner, projectId);
        const project = await env.OAUTH_KV.get<NexusProject>(key, "json");
        if (!project) throw new Error("Project not found for this account.");
        project.storyboard = { script, aspectRatio, targetDurationSeconds, scenes };
        project.revision += 1;
        project.updatedAt = new Date().toISOString();
        await env.OAUTH_KV.put(key, JSON.stringify(project));
      }
      return {
        content: [{
          type: "text" as const,
          text: JSON.stringify({
            status: "storyboard_created",
            executionMode: "planning_only",
            aspectRatio,
            targetDurationSeconds,
            scenes,
            note: "Scene prompts are planning text only; connect an image/video provider to generate assets.",
          }, null, 2),
        }],
      };
    },
  );

